-- 견적서 만들기(사용자 지시 2026-10-29). 세 가지를 더한다.
--
-- 1) business_profiles — 마케터 본인의 사업장 정보(마이페이지 '내 정보'). 견적서 공급자 칸에 자동으로 들어간다.
-- 2) advertiser_profiles — 광고주 정보. 광고주 '로그인 계정'(users.role=ADVERTISER)과 별개로 저장한다:
--    계정은 이메일·비밀번호가 필수이고 요금제 광고주 수 상한에 걸리므로, 견적만 보내는 업체까지 계정으로
--    만들 수는 없다. 포털 계정이 있으면 advertiser_user_id 로 선택적으로 연결한다.
-- 3) quotes — 견적서. 받는 쪽·공급자 정보를 견적서 안에 **복사해 저장**한다(recipient/supplier JSON) —
--    수동 입력 견적서도 그대로 남고, 광고주 정보·사업장 정보를 나중에 고쳐도 이미 만든 견적서는 바뀌지 않는다.

create table business_profiles (
    user_id       bigint primary key references users (id) on delete cascade,
    company_name  varchar(120) not null default '',
    ceo_name      varchar(60)  not null default '',
    biz_no        varchar(20)  not null default '',
    address       varchar(255) not null default '',
    phone         varchar(40)  not null default '',
    email         varchar(255) not null default '',
    bank_account  varchar(255) not null default '',
    updated_at    timestamp(6) with time zone not null
);

create table advertiser_profiles (
    id                  bigint generated by default as identity primary key,
    owner_id            bigint not null references users (id) on delete cascade,
    company_name        varchar(120) not null,
    ceo_name            varchar(60)  not null default '',
    biz_no              varchar(20)  not null default '',
    contact_name        varchar(60)  not null default '',
    phone               varchar(40)  not null default '',
    email               varchar(255) not null default '',
    address             varchar(255) not null default '',
    memo                varchar(500) not null default '',
    -- 연결된 광고주 포털 계정. 계정을 지워도 광고주 정보와 견적 이력은 남긴다.
    advertiser_user_id  bigint references users (id) on delete set null,
    created_at          timestamp(6) with time zone not null,
    updated_at          timestamp(6) with time zone not null
);
create index idx_advertiser_profiles_owner on advertiser_profiles (owner_id);
-- 계정 하나에 광고주 정보 하나.
create unique index uq_advertiser_profiles_account on advertiser_profiles (advertiser_user_id)
    where advertiser_user_id is not null;

-- 이미 있는 광고주 계정마다 광고주 정보를 하나씩 만들어 연결해 둔다(회사명이 없으면 이름).
insert into advertiser_profiles (owner_id, company_name, contact_name, phone, email, memo, advertiser_user_id,
                                 created_at, updated_at)
select u.parent_user_id,
       left(coalesce(nullif(trim(u.company), ''), u.name), 120),
       left(coalesce(u.name, ''), 60),
       left(coalesce(u.phone, ''), 40),
       u.email,
       coalesce(u.memo, ''),
       u.id,
       now(),
       now()
from users u
where u.role = 'ADVERTISER'
  and u.parent_user_id is not null;

create table quotes (
    id                     bigint generated by default as identity primary key,
    owner_id               bigint not null references users (id) on delete cascade,
    -- 광고주 정보를 지워도 견적서는 남긴다(받는 쪽 정보는 recipient 에 복사돼 있다).
    advertiser_profile_id  bigint references advertiser_profiles (id) on delete set null,
    quote_no               varchar(30)  not null,
    title                  varchar(200) not null,
    issue_date             date not null,
    valid_until            date,
    status                 varchar(20) not null,   -- DRAFT | ISSUED | ACCEPTED | REJECTED
    vat_mode               varchar(20) not null,   -- EXCLUDED | INCLUDED | EXEMPT
    supplier               jsonb not null,
    recipient              jsonb not null,
    items                  jsonb not null,
    notes                  jsonb not null,
    supply_total           bigint not null,
    vat_total              bigint not null,
    grand_total            bigint not null,
    issued_at              timestamp(6) with time zone,
    created_at             timestamp(6) with time zone not null,
    updated_at             timestamp(6) with time zone not null
);
create unique index uq_quotes_owner_no on quotes (owner_id, quote_no);
create index idx_quotes_owner_date on quotes (owner_id, issue_date desc);
create index idx_quotes_advertiser_profile on quotes (advertiser_profile_id);
