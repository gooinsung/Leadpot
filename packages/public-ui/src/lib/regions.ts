export const ALL_SIDO: readonly string[] = REGIONS.map((r) => r.sido);

/** 시/도의 구/시 목록. 모르는 시/도면 빈 배열. */
export function sigunguOf(sido: string): readonly string[] {
  return REGIONS.find((r) => r.sido === sido)?.sigungu ?? [];
}

/** 이 항목에서 보여줄 시/도 — 마케터가 고른 것(`options.regions`, 전국 순서 유지). 비었거나 모르는 값뿐이면 전국. */
export function allowedSido(regions: unknown): string[] {
  const picked = Array.isArray(regions) ? regions.filter((s): s is string => typeof s === "string") : [];
  const list = ALL_SIDO.filter((s) => picked.includes(s));
  return list.length ? list : [...ALL_SIDO];
}

/** 저장값 `"서울 강남구"` ↔ [시/도, 구/시]. 구/시에는 공백이 없으므로 첫 공백으로 나눈다. */
export function splitRegion(value: string | undefined | null): [string, string] {
  const v = (value ?? "").trim();
  const i = v.indexOf(" ");
  return i < 0 ? [v, ""] : [v.slice(0, i), v.slice(i + 1).trim()];
}

export function joinRegion(sido: string, sigungu: string): string {
  return sigungu ? `${sido} ${sigungu}` : sido;
}

/** 시/도를 골랐는데 아래 단계가 있는 곳이면 구/시까지 골라야 완성이다(세종은 시/도만으로 완성). */
export function isRegionComplete(value: string | undefined | null): boolean {
  const [sido, sigungu] = splitRegion(value);
  if (!sido) return false;
  const subs = sigunguOf(sido);
  return subs.length === 0 ? true : subs.includes(sigungu);
}
